let _lang = $state('en');
export const lang = {
  get value() {
    return _lang;
  },
  set value(v) {
    _lang = v;
  },
};

export function setLang(l) {
  _lang = l;
}

export function t(key) {
  return I18N[_lang][key] ?? key;
}

export function fmt(str, vars) {
  let s = str;
  for (const [k, v] of Object.entries(vars)) {
    s = s.split('{' + k + '}').join(String(v));
  }
  return s;
}
